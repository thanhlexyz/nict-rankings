def rebuild_site():
    """Rebuild frontend/data and the Hugo output after new data lands. A lock keeps two finishing jobs from building at once
    (the one that finds it taken skips: the other's build already sees both results, or the final build catches up)."""
    import subprocess
    import sys
    cmd = f"{sys.executable} {BACKEND / 'build_site_data.py'} >/dev/null 2>&1 && cd {FRONTEND} && hugo --quiet >/dev/null 2>&1"
    subprocess.run(["flock", "-n", "/tmp/nict-rankings-build.lock", "sh", "-c", cmd], capture_output=True)
